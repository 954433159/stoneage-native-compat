"""Deploy the reviewed task resource to this local copy after closing the game."""
import ctypes
from ctypes import wintypes
import json
import os
from prepare_client_tasks import (ROOT, LOCAL, ORIGINAL, CANDIDATE, EXPECTED_SHA256,
                                  build_candidate, require, sha256)


def main():
    original = ORIGINAL.read_bytes()
    candidate, report = build_candidate(original)
    require(CANDIDATE.read_bytes() == candidate, 'Reviewed candidate differs from regenerated bytes')
    current = LOCAL.read_bytes()
    require(current in (original, candidate), 'Unrecorded local task resource; refusing to replace')
    if os.name == 'nt':
        kernel = ctypes.WinDLL('kernel32', use_last_error=True)
        kernel.OpenProcess.restype = ctypes.c_void_p
        kernel.CloseHandle.argtypes = [ctypes.c_void_p]
        kernel.GetExitCodeProcess.argtypes = [ctypes.c_void_p, ctypes.POINTER(wintypes.DWORD)]
        for name in ('client.pid', 'observer-client.pid'):
            path = ROOT / 'runtime' / name
            if path.exists():
                handle = kernel.OpenProcess(0x1000, False, int(path.read_text()))
                if not handle:
                    require(ctypes.get_last_error() == 87,
                            'Cannot determine whether a local game process is running')
                if handle:
                    code = wintypes.DWORD()
                    try:
                        exited = kernel.GetExitCodeProcess(handle, ctypes.byref(code)) and code.value != 259
                    finally:
                        kernel.CloseHandle(handle)
                    require(exited, 'Close both local game clients normally before applying task resources')
    backup = ROOT / 'backups' / 'client-task-original' / 'task.bin'
    backup.parent.mkdir(parents=True, exist_ok=True)
    if backup.exists():
        require(backup.read_bytes() == original, 'Original task backup differs')
    else:
        with backup.open('xb') as stream:
            stream.write(original)
    if current != candidate:
        temporary = LOCAL.with_name('task.bin.prepared')
        with temporary.open('xb') as stream:
            stream.write(candidate)
        require(LOCAL.read_bytes() == current, 'Local resource changed during preparation')
        temporary.replace(LOCAL)
    require(LOCAL.read_bytes() == candidate and ORIGINAL.read_bytes() == original,
            'Task resource deployment verification failed')
    result = {'deployed': True, 'original_sha256': EXPECTED_SHA256,
              'local_sha256': sha256(candidate), 'existing_subtasks_preserved': 137,
              'backup': str(backup), 'original_unchanged': True}
    (ROOT / 'evidence/client-task-applied.json').write_text(json.dumps(result, indent=2) + '\n')
    print(json.dumps(result))


if __name__ == '__main__':
    main()
